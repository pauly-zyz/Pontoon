// Copies ABIs from the Foundry build output (../contracts/out) into lib/abis/*.ts.
// Run `forge build` in ../contracts first, then `npm run abis`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "..", "contracts", "out");

// [source file, contract name, exported name]
const targets = [
  ["PontoonLauncher.sol", "PontoonLauncher", "PontoonLauncherAbi"],
  ["TokenRegistry.sol", "TokenRegistry", "TokenRegistryAbi"],
  ["FeeVault.sol", "FeeVault", "FeeVaultAbi"],
  ["BuybackExecutor.sol", "BuybackExecutor", "BuybackExecutorAbi"],
  ["HolderRewards.sol", "HolderRewards", "HolderRewardsAbi"],
  ["PlatformTreasury.sol", "PlatformTreasury", "PlatformTreasuryAbi"],
  ["CTOManager.sol", "CTOManager", "CTOManagerAbi"],
  // Live Pons V2 (Robinhood Chain): launch factory + per-token bonding curve.
  ["IPonsV2Live.sol", "IPonsV2LaunchFactory", "PonsV2FactoryAbi"],
  ["IPonsV2Live.sol", "IPonsV2Curve", "PonsV2CurveAbi"],
];

for (const [file, name, exportName] of targets) {
  const { abi } = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  const body = `// Generated by scripts/sync-abis.mjs from contracts/out/${file}/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(root, "lib", "abis", `${exportName}.ts`), body);
  console.log(`lib/abis/${exportName}.ts`);
}
